    <script>
        document.addEventListener('DOMContentLoaded', function () {
            const contactForm = document.getElementById('contact-form');

            if (contactForm) {
                contactForm.addEventListener('submit', function (e) {
                    e.preventDefault();

                    const formData = new FormData(this);

                    // Debug: Log all form data
                    console.log('=== FORM DATA DEBUG ===');
                    for (let [key, value] of formData.entries()) {
                        console.log(`${key}: "${value}" (length: ${value.length})`);
                    }
                    console.log('=== END DEBUG ===');

                    fetch("{{ route('comments.store') }}", {
                        method: 'POST',
                        body: formData,
                        headers: {
                            'X-Requested-With': 'XMLHttpRequest',
                            'Accept': 'application/json'
                        }
                    })
                        .then(response => {
                            console.log('Response status:', response.status);
                            return response.json().then(data => {
                                return { status: response.status, data: data };
                            });
                        })
                        .then(({ status, data }) => {
                            console.log('Response data:', data);

                            if (status === 200 && data.success) {
                                // Get the message from FormData
                                const message = formData.get('message');
                                const name = formData.get('name');
                                const email = formData.get('email');

                                // Add new comment to comments container
                                const commentsContainer = document.getElementById('comments-container');
                                const newCommentHTML = `
                                <div class="col-lg-6 col-sm-12 col-xs-12 wow fadeInUp" data-wow-duration="1s"
                                    data-wow-delay="0.1s" data-wow-offset="0">
                                    <div class="single_testimonial">
                                        <div class="testimonial_img">
                                        <img src="assets/img/icon/profile.png" alt="profile" />
                                        </div>
                                        <p>${message}</p>
                                        <h4>${name}</h4>
                                        ${email ? `<h5>${email}</h5>` : ''}
                                    </div>
                                </div>
                            `;

                                // Remove empty message if exists
                                const emptyMessage = commentsContainer.querySelector('.col-lg-12.text-center');
                                if (emptyMessage) {
                                    emptyMessage.remove();
                                }

                                // Add new comment at the beginning
                                commentsContainer.insertAdjacentHTML('afterbegin', newCommentHTML);

                                // Reset form
                                contactForm.reset();

                                // Show success message
                                alert('Komentar berhasil ditambahkan!');
                            } else if (status === 422 && data.errors) {
                                // Handle validation errors
                                let errorMessage = 'Validasi gagal:\n';
                                for (let field in data.errors) {
                                    errorMessage += '- ' + field + ': ' + data.errors[field].join(', ') + '\n';
                                }
                                console.error('Validation errors:', data.errors);
                                alert(errorMessage);
                            } else {
                                alert('Gagal menambahkan komentar: ' + (data.message || 'Unknown error'));
                            }
                        })
                        .catch(error => {
                            console.error('Error:', error);
                            alert('Terjadi kesalahan saat mengirim komentar: ' + error.message);
                        });
                });
            }
        });
    </script>
